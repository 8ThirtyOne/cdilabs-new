	     <h3>PhiP-Seq <span class="line-break">Sample Requirements</span></h3>
 
         <div class="card-layout card4-wrapper">

             <div class="column-box">
             	<h4>Serum or plasma</h4>
             	<p>20 μL aliquot per sample</p>
             </div>
             <div class="column-box">
             	<h4>Cerebrospinal fluid (CSF)</h4>
		<p>250 μL aliquot per sample</p>
             </div>
             <div class="column-box">
             	<h4>Other antibodies <span class="line-break">(IgG monoclonals, B cell supernatants, etc)</span></h4>
		<p>250 μL aliquot per sample <span class="line-break">(0.01 mg/mL concentration)</span></p>
             </div>
             <div class="column-box">
             	<h4>12 sample minimum</h4>
                <p>In multiples of x12 samples <span class="line-break">(<i>i.e.</i>, x12, x24, x36, 48x – full rows of a standard 96-well plate), and any number after 48 samples</span></p>
             </div>
          </div>

